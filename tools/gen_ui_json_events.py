"""Generate main/TemcoScreen/ui_json_events.c/.h

Maps a SquareLine/EEZ design name to the compiled `ui_event_<Name>()` handler so
the JSON renderer can forward LVGL events to the firmware's real behaviour
(save settings, apply config, start scans, set modes...) without needing the
event logic to be described in the exported JSON.

Run from the repository root:  python tools/gen_ui_json_events.py
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UI = os.path.join(ROOT, "main", "TemcoScreen")

RE_HANDLER = re.compile(r"^\s*void\s+ui_event_([A-Za-z0-9_]+)\s*\(\s*lv_event_t\s*\*\s*e\s*\)", re.M)
RE_ACCEPT = re.compile(r"lv_textarea_set_accepted_chars\(\s*ui_([A-Za-z0-9_]+)\s*,\s*\"((?:[^\"\\]|\\.)*)\"\s*\)")
RE_MAXLEN = re.compile(r"lv_textarea_set_max_length\(\s*ui_([A-Za-z0-9_]+)\s*,\s*(\d+)\s*\)")


def c_bytes(s):
    """Emit a C string literal with every byte escaped (safe for UTF-8)."""
    raw = s.encode("utf-8")
    return '"' + "".join("\\x%02x" % b for b in raw) + '"'


def unescape_c(s):
    """Undo the handful of C escapes that appear in these literals, without
    touching non-ASCII bytes (the source is already decoded as UTF-8)."""
    out = []
    i = 0
    while i < len(s):
        c = s[i]
        if c == "\\" and i + 1 < len(s):
            n = s[i + 1]
            out.append({"n": "\n", "t": "\t", "r": "\r", '"': '"', "\\": "\\", "'": "'"}.get(n, n))
            i += 2
        else:
            out.append(c)
            i += 1
    return "".join(out)


def collect_inputs():
    """design name -> (accepted_chars, max_length) from the compiled sources."""
    inputs = {}
    for fn in sorted(os.listdir(UI)):
        if not (fn.startswith("ui_") and fn.endswith(".c")):
            continue
        if fn.startswith("ui_json"):
            continue
        src = open(os.path.join(UI, fn), encoding="utf-8", errors="replace").read()
        for m in RE_ACCEPT.finditer(src):
            inputs.setdefault(m.group(1), [None, 0])[0] = unescape_c(m.group(2))
        for m in RE_MAXLEN.finditer(src):
            inputs.setdefault(m.group(1), [None, 0])[1] = int(m.group(2))
    return inputs


def collect():
    handlers = {}
    for fn in sorted(os.listdir(UI)):
        if not (fn.startswith("ui_") and fn.endswith(".c")):
            continue
        if fn in ("ui_json_render.c", "ui_json_bind.c", "ui_json_events.c"):
            continue
        src = open(os.path.join(UI, fn), encoding="utf-8", errors="replace").read()
        for m in RE_HANDLER.finditer(src):
            handlers.setdefault(m.group(1), fn)
    return handlers


HEADER = """/* GENERATED by tools/gen_ui_json_events.py - do not edit by hand. */
#pragma once

#include "lvgl.h"

typedef void (*ui_json_event_fn)(lv_event_t *e);

/* Returns the compiled handler for a design name, or NULL. */
ui_json_event_fn ui_json_events_lookup(const char *name);

/* Textarea input rules that the exported JSON does not carry. */
typedef struct {
    const char *name;
    const char *accepted;  /* NULL when the design sets none */
    int max_length;        /* 0 when the design sets none */
} ui_json_input_t;

/* Returns the input rules for a design name, or NULL. */
const ui_json_input_t *ui_json_input_lookup(const char *name);
"""


def main():
    handlers = collect()
    names = sorted(handlers)
    inputs = collect_inputs()

    with open(os.path.join(UI, "ui_json_events.h"), "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER)

    with open(os.path.join(UI, "ui_json_events.c"), "w", encoding="utf-8", newline="\n") as f:
        f.write("/* GENERATED by tools/gen_ui_json_events.py - do not edit by hand. */\n")
        f.write('/* %d design names map to a compiled ui_event_* handler, %d carry input rules. */\n\n'
                % (len(names), len(inputs)))
        f.write('#include <string.h>\n\n#include "ui_json_events.h"\n\n')
        for n in names:
            f.write("extern void ui_event_%s(lv_event_t *e);\n" % n)
        f.write("\ntypedef struct {\n    const char *name;\n    ui_json_event_fn fn;\n} event_bind_t;\n\n")
        f.write("static const event_bind_t s_events[] = {\n")
        for n in names:
            f.write('    {"%s", ui_event_%s},\n' % (n, n))
        f.write("};\n\n")
        f.write("""ui_json_event_fn ui_json_events_lookup(const char *name)
{
    if (!name || !name[0]) return NULL;
    for (size_t i = 0; i < sizeof(s_events) / sizeof(s_events[0]); i++) {
        if (strcmp(s_events[i].name, name) == 0) return s_events[i].fn;
    }
    return NULL;
}

static const ui_json_input_t s_inputs[] = {
""")
        for n in sorted(inputs):
            accepted, maxlen = inputs[n]
            a = c_bytes(accepted) if accepted else "NULL"
            f.write('    {"%s", %s, %d},\n' % (n, a, maxlen))
        f.write("""};

const ui_json_input_t *ui_json_input_lookup(const char *name)
{
    if (!name || !name[0]) return NULL;
    for (size_t i = 0; i < sizeof(s_inputs) / sizeof(s_inputs[0]); i++) {
        if (strcmp(s_inputs[i].name, name) == 0) return &s_inputs[i];
    }
    return NULL;
}
""")

    print("generated ui_json_events.{c,h}: %d handlers, %d input rules" % (len(names), len(inputs)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
