#!/usr/bin/env python3
"""Regenerate main/TemcoScreen/ui_json_bind.c.

The compiled SquareLine screens keep every widget in a global (``ui_Name`` for
the object, ``uic_Name`` for the "current" alias used by the runtime update
code).  The runtime JSON renderer re-creates the same widgets from the deployed
JSON, so this table lets it point those globals at the JSON objects and hand
them back when the JSON UI is torn down.

Usage:  python tools/gen_ui_json_bind.py
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCREEN_DIR = os.path.join(ROOT, "main", "TemcoScreen")
OUT_C = os.path.join(SCREEN_DIR, "ui_json_bind.c")

# screen containers are never rebound: navigation must keep using the compiled
# screens when the JSON UI is inactive
SCREENS = {
    "HomeScreen", "StartUpScreen", "MainMenu", "WifiConfig", "NetworkConfig",
    "Protocols", "Parameters", "Time", "ScheduleScreen", "ScheduleEditScreen",
    "HolidayCalenderScreen", "WireGuardScreen", "DdnsScreen",
}

DEF_RE = re.compile(r"^lv_obj_t\s*\*\s*(ui_|uic_)([A-Za-z0-9_]+)\s*(?:=|;)", re.M)


def collect():
    names = {}
    for fn in sorted(os.listdir(SCREEN_DIR)):
        if not fn.endswith(".c") or not fn.startswith("ui_") or fn.startswith("ui_json"):
            continue
        with open(os.path.join(SCREEN_DIR, fn), encoding="utf-8", errors="ignore") as fh:
            src = fh.read()
        for match in DEF_RE.finditer(src):
            prefix, name = match.group(1), match.group(2)
            if name.startswith("_") or name in SCREENS:
                continue
            names.setdefault(name, set()).add(prefix + name)
    return names


HEADER = """/* Auto-generated by tools/gen_ui_json_bind.py - do not edit by hand.
 *
 * Rebinding table between the compiled SquareLine widget objects and the
 * runtime JSON widgets that carry the same design name.  The compiled
 * firmware updates live values through these globals (ui_X / uic_X), so
 * pointing them at the JSON widgets makes the existing update logic drive
 * the deployed UI without touching any of the screen code.
 */
#include <string.h>
#include "lvgl.h"
#include "ui.h"
#include "ui_json_bind.h"

typedef struct {
    const char *name;
    lv_obj_t **slot;
    lv_obj_t *orig;
} ui_json_bind_entry_t;

#define UI_JSON_BIND(nm, sym) { nm, &sym, NULL }

"""

ARRAY_HEAD = """static ui_json_bind_entry_t s_bind[] = {
"""

FOOTER = """};

#define UI_JSON_BIND_COUNT (sizeof(s_bind) / sizeof(s_bind[0]))

static bool s_snapshotted;

void ui_json_bind_snapshot(void)
{
    for (size_t i = 0; i < UI_JSON_BIND_COUNT; i++) {
        s_bind[i].orig = *s_bind[i].slot;
    }
    s_snapshotted = true;
}

void ui_json_bind_restore(void)
{
    if (!s_snapshotted) return;
    for (size_t i = 0; i < UI_JSON_BIND_COUNT; i++) {
        *s_bind[i].slot = s_bind[i].orig;
    }
}

bool ui_json_bind_apply(const char *name, lv_obj_t *obj)
{
    if (!name || !obj) return false;
    bool bound = false;
    for (size_t i = 0; i < UI_JSON_BIND_COUNT; i++) {
        if (!strcmp(s_bind[i].name, name)) {
            *s_bind[i].slot = obj;
            bound = true;
        }
    }
    return bound;
}

size_t ui_json_bind_count(void)
{
    return UI_JSON_BIND_COUNT;
}

/* The compiled object this design name maps to (captured at boot), so the
 * renderer can inherit flags/styles the JSON export does not carry. */
lv_obj_t *ui_json_bind_original(const char *name)
{
    if (!name || !name[0]) return NULL;
    for (size_t i = 0; i < UI_JSON_BIND_COUNT; i++) {
        if (!strcmp(s_bind[i].name, name) && s_bind[i].orig) return s_bind[i].orig;
    }
    return NULL;
}
"""


def main():
    names = collect()
    rows = []
    externs = []
    seen = set()
    for name in sorted(names):
        for symbol in sorted(names[name]):
            rows.append('    UI_JSON_BIND("%s", %s),' % (name, symbol))
            if symbol not in seen:
                seen.add(symbol)
                externs.append("extern lv_obj_t * %s;" % symbol)
    body = HEADER + "\n".join(externs) + "\n\n" + ARRAY_HEAD
    with open(OUT_C, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(body + "\n".join(rows) + "\n" + FOOTER)
    print("wrote %s (%d names, %d slots)" % (OUT_C, len(names), len(rows)))


if __name__ == "__main__":
    main()
