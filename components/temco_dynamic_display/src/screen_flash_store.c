static void log_spiffs_usage(const char *when)
{
    size_t total = 0, used = 0;
    if (esp_spiffs_info(PARTITION_LABEL, &total, &used) == ESP_OK) {
        ESP_LOGI(TAG, "SPIFFS %s: used=%u KB, free=%u KB, total=%u KB",
                 when,
                 (unsigned)(used / 1024),
                 (unsigned)((total > used) ? ((total - used) / 1024) : 0),
                 (unsigned)(total / 1024));
    }
}

/*
 * Crash-safe replace: the payload is written to <path>.tmp, fsynced, and only
 * then renamed onto <path>. A power cut therefore leaves either the previous
 * file or one complete .tmp file - never a truncated screen.
 * recover_pending_writes_in() promotes a complete .tmp on the next boot.
 *
 * The destination is unlinked just before the rename because SPIFFS keeps the
 * old pages allocated when a file is overwritten in place, which makes
 * fwrite() return a short count (ENOSPC) even for a valid payload.
 */
static esp_err_t write_file_replace(const char *path, const char *data, size_t len)
{
    if (!path || !data) return ESP_ERR_INVALID_ARG;

    struct stat st;
    size_t old_size = 0;
    bool exists = (stat(path, &st) == 0);
    if (exists && st.st_size > 0) {
        old_size = (size_t)st.st_size;
    }

    size_t total = 0, used = 0;
    if (esp_spiffs_info(PARTITION_LABEL, &total, &used) == ESP_OK) {
        size_t used_after_unlink = (used > old_size) ? (used - old_size) : 0;
        size_t free_after_unlink = (total > used_after_unlink) ? (total - used_after_unlink) : 0;
        if (free_after_unlink < len + SPIFFS_WRITE_OVERHEAD) {
            ESP_LOGE(TAG,
                     "Not enough SPIFFS space for %s: need %u bytes, free after replace ~%u (used=%u total=%u old=%u)",
                     path, (unsigned)len, (unsigned)free_after_unlink,
                     (unsigned)used, (unsigned)total, (unsigned)old_size);
            log_spiffs_usage("before rejected write");
            return ESP_ERR_NO_MEM;
        }
    }

    char tmp_path[132];
    snprintf(tmp_path, sizeof(tmp_path), "%s.tmp", path);

    FILE *f = fopen(tmp_path, "wb");
    if (!f) {
        ESP_LOGE(TAG, "Failed to open for writing: %s (errno=%d)", path, errno);
        return ESP_FAIL;
    }

    size_t written = 0;
    while (written < len) {
        size_t chunk = len - written;
        if (chunk > WRITE_CHUNK_SIZE) chunk = WRITE_CHUNK_SIZE;
        size_t n = fwrite(data + written, 1, chunk, f);
        if (n == 0) {
            ESP_LOGE(TAG, "fwrite stopped at %u/%u for %s (ferror=%d errno=%d)",
                     (unsigned)written, (unsigned)len, path, ferror(f), errno);
            break;
        }
        written += n;
    }

    int flush_err = fflush(f);
    int sync_err = 0;
    int fd = fileno(f);
    if (fd >= 0) {
        sync_err = fsync(fd);
    }
    int stream_err = ferror(f);
    fclose(f);

    if (written != len || flush_err != 0 || sync_err != 0 || stream_err) {
        ESP_LOGE(TAG, "Incomplete write %s (%u/%u) flush=%d sync=%d ferror=%d errno=%d",
                 tmp_path, (unsigned)written, (unsigned)len, flush_err, sync_err, stream_err, errno);
        remove(tmp_path);
        log_spiffs_usage("after failed write");
        return ESP_FAIL;
    }

    if (exists && remove(path) != 0 && errno != ENOENT) {
        ESP_LOGW(TAG, "Failed to unlink previous file: %s (errno=%d)", path, errno);
    }
    if (rename(tmp_path, path) != 0) {
        ESP_LOGE(TAG, "Failed to promote %s -> %s (errno=%d)", tmp_path, path, errno);
        remove(tmp_path);
        return ESP_FAIL;
    }

    return ESP_OK;
}

static bool file_looks_complete(const char *path)
{
    struct stat st;
    if (stat(path, &st) != 0 || st.st_size <= 0) {
        return false;
    }
    FILE *f = fopen(path, "rb");
    if (!f) {
        return false;
    }
    /* Only the first and the last non-blank byte matter. Reading the whole file
     * here blocked the display task long enough to trip the task watchdog. */
    bool ok = false;
    int first = 0;
    if (fread(&first, 1, 1, f) == 1 && first == '{') {
        char tail[64];
        size_t want = sizeof(tail);
        if ((size_t)st.st_size < want) {
            want = (size_t)st.st_size;
        }
        if (fseek(f, (long)((size_t)st.st_size - want), SEEK_SET) == 0 &&
            fread(tail, 1, want, f) == want) {
            for (size_t i = want; i-- > 0;) {
                char c = tail[i];
                if (c == ' ' || c == '\t' || c == '\r' || c == '\n' || c == '\0') {
                    continue;
                }
                ok = (c == '}');
                break;
            }
        }
    }
    fclose(f);
    return ok;
}

static void recover_pending_writes_in(const char *dir)
{
    DIR *d = opendir(dir);
    if (!d) {
        return;
    }
    struct dirent *e;
    while ((e = readdir(d)) != NULL) {
        const char *n = e->d_name;
        size_t nl = strlen(n);
        if (nl < 5 || strcmp(n + nl - 4, ".tmp") != 0) {
            continue;
        }
        char tmp_path[320];
        char final_path[320];
        size_t name_len = (nl > 250) ? 250 : nl - 4;
        snprintf(tmp_path, sizeof(tmp_path), "%s/%s", dir, n);
        snprintf(final_path, sizeof(final_path), "%s/%.*s", dir, (int)name_len, n);

        struct stat st_tmp, st_final;
        if (stat(tmp_path, &st_tmp) != 0 || st_tmp.st_size <= 0) {
            remove(tmp_path);
            continue;
        }
        if (stat(final_path, &st_final) == 0 && st_final.st_size > 0) {
            remove(tmp_path);
            continue;
        }
        if (rename(tmp_path, final_path) == 0) {
            ESP_LOGW(TAG, "Recovered interrupted write: %s", final_path);
        } else {
            ESP_LOGE(TAG, "Could not recover %s (errno=%d)", tmp_path, errno);
        }
    }
    closedir(d);
}

static void ensure_directories_exist(void)
{
    struct stat st;
    if (stat(SCREENS_DIR, &st) != 0) {
        mkdir(SCREENS_DIR, 0755);
    }
    if (stat(IMAGES_DIR, &st) != 0) {
        mkdir(IMAGES_DIR, 0755);
    }
}

/* EMBED_TXTFILES appends a NUL terminator; the stored file must not include it */
static size_t embedded_text_len(const char *start, const char *end)
{
    size_t len = (size_t)(end - start);
    if (len && start[len - 1] == '\0') {
        len--;
    }
    return len;
}

static esp_err_t seed_default_screens_if_empty(void)
{
    ensure_directories_exist();

    for (size_t i = 0; i < DEFAULT_SCREENS_COUNT; i++) {
        char path[128];
        snprintf(path, sizeof(path), "%s/%s.json", SCREENS_DIR, DEFAULT_SCREENS[i].name);

        if (!file_looks_complete(path)) {
            ESP_LOGI(TAG, "Seeding default screen: %s", DEFAULT_SCREENS[i].name);
            size_t len = embedded_text_len(DEFAULT_SCREENS[i].start, DEFAULT_SCREENS[i].end);
            if (write_file_replace(path, DEFAULT_SCREENS[i].start, len) != ESP_OK) {
                ESP_LOGE(TAG, "Failed to create default screen file: %s", path);
            }
        }
    }

    for (size_t i = 0; i < DEFAULT_IMAGES_COUNT; i++) {
        char path[128];
        snprintf(path, sizeof(path), "%s/%s.json", IMAGES_DIR, DEFAULT_IMAGES[i].name);

        if (!file_looks_complete(path)) {
            ESP_LOGI(TAG, "Seeding default image: %s", DEFAULT_IMAGES[i].name);
            size_t len = embedded_text_len(DEFAULT_IMAGES[i].start, DEFAULT_IMAGES[i].end);
            if (write_file_replace(path, DEFAULT_IMAGES[i].start, len) != ESP_OK) {
                ESP_LOGE(TAG, "Failed to create default image file: %s", path);
            }
        }
    }
    return ESP_OK;
}

static esp_err_t mount_spiffs(void)
{
    esp_err_t ret = esp_vfs_spiffs_register(&s_spiffs_conf);
    if (ret != ESP_OK) {
        if (ret == ESP_FAIL) {
            ESP_LOGE(TAG, "Failed to mount or format filesystem");
        } else if (ret == ESP_ERR_NOT_FOUND) {
            ESP_LOGE(TAG, "Failed to find SPIFFS partition 'screen_data'");
        } else {
            ESP_LOGE(TAG, "Failed to initialize SPIFFS (%s)", esp_err_to_name(ret));
        }
        return ret;
    }
    s_is_mounted = true;
    return ESP_OK;
}

static size_t count_default_files_present(const default_resource_entry_t *entries, size_t count, const char *dir)
{
    size_t present = 0;
    for (size_t i = 0; i < count; i++) {
        char path[128];
        struct stat st;
        snprintf(path, sizeof(path), "%s/%s.json", dir, entries[i].name);
        if (stat(path, &st) == 0 && st.st_size > 0) {
            present++;
        }
    }
    return present;
}

esp_err_t screen_store_mount(void)
{
    if (s_is_mounted) return ESP_OK;

    ESP_LOGI(TAG, "Initializing SPIFFS partition screen_data");

    esp_err_t ret = mount_spiffs();
    if (ret != ESP_OK) {
        return ret;
    }

    log_spiffs_usage("after mount");
    esp_err_t txn_err = screen_txn_init();
    if (txn_err != ESP_OK) {
        ESP_LOGE(TAG, "Screen transaction store failed to initialise (%s)", esp_err_to_name(txn_err));
        return txn_err;
    }
    recover_pending_writes_in(SCREENS_DIR);
    recover_pending_writes_in(IMAGES_DIR);
    return ESP_OK;
}

/* Validating ~40 embedded files takes several seconds; callers that must stay
 * responsive (the REST server) mount first and seed afterwards. */
esp_err_t screen_store_seed_defaults(void)
{
    if (!s_is_mounted) return ESP_ERR_INVALID_STATE;
    seed_default_screens_if_empty();
    log_spiffs_usage("after seed");
    return ESP_OK;
}

esp_err_t screen_store_init(void)
{
    esp_err_t ret = screen_store_mount();
    if (ret != ESP_OK) {
        return ret;
    }
    return screen_store_seed_defaults();
}

bool screen_store_is_ready(void)
{
    return s_is_mounted;
}

esp_err_t screen_store_get_screen(const char *name, char **out_buf, size_t *out_size)
{
    if (!s_is_mounted || !name || !out_buf) return ESP_ERR_INVALID_ARG;

    char path[128];
    snprintf(path, sizeof(path), "%s/%s.json", SCREENS_DIR, name);

    FILE *f = fopen(path, "rb");
    if (!f) {
        ESP_LOGW(TAG, "Screen not found: %s", path);
        return ESP_ERR_NOT_FOUND;
    }

    fseek(f, 0, SEEK_END);
    long sz = ftell(f);
    fseek(f, 0, SEEK_SET);

    if (sz <= 0) {
        fclose(f);
        ESP_LOGW(TAG, "Screen file empty or truncated: %s", path);
        return ESP_ERR_INVALID_SIZE;
    }

    char *buf = (char *)malloc(sz + 1);
    if (!buf) {
        fclose(f);
        return ESP_ERR_NO_MEM;
    }

    size_t read_bytes = fread(buf, 1, sz, f);
    fclose(f);

    buf[read_bytes] = '\0';
    *out_buf = buf;
    if (out_size) *out_size = read_bytes;

    return ESP_OK;
}

esp_err_t screen_store_save_screen(const char *name, const char *json_data, size_t len)
{
    if (!s_is_mounted || !name || !json_data) return ESP_ERR_INVALID_ARG;

    ensure_directories_exist();

    if (len == 0) len = strlen(json_data);

    char path[128];
    snprintf(path, sizeof(path), "%s/%s.json", SCREENS_DIR, name);

    esp_err_t err = write_file_replace(path, json_data, len);
    if (err != ESP_OK) {
        ESP_LOGE(TAG, "Failed to write complete screen data: %s (%u bytes) err=%s",
                 name, (unsigned)len, esp_err_to_name(err));
        return err;
    }

    ESP_LOGI(TAG, "Saved screen to flash: %s (%u bytes)", name, (unsigned)len);
    return ESP_OK;
}

esp_err_t screen_store_delete_screen(const char *name)
{
    if (!s_is_mounted || !name) return ESP_ERR_INVALID_ARG;

    char path[128];
    snprintf(path, sizeof(path), "%s/%s.json", SCREENS_DIR, name);

    if (remove(path) == 0) {
        ESP_LOGI(TAG, "Deleted screen: %s", name);
        return ESP_OK;
    }

    return ESP_ERR_NOT_FOUND;
}

esp_err_t screen_store_list_screens(char names[][64], size_t max_count, size_t *out_count)
{
    if (!s_is_mounted || !names || !out_count) return ESP_ERR_INVALID_ARG;

    size_t count = 0;
    DIR *dir = opendir(SCREENS_DIR);
    if (!dir) {
        *out_count = 0;
        return ESP_OK;
    }

    struct dirent *entry;
    while ((entry = readdir(dir)) != NULL && count < max_count) {
        if (entry->d_type == DT_REG || entry->d_type == DT_UNKNOWN) {
            char *dot = strrchr(entry->d_name, '.');
            if (dot && strcmp(dot, ".json") == 0) {
                size_t name_len = dot - entry->d_name;
                if (name_len < 64) {
                    strncpy(names[count], entry->d_name, name_len);
                    names[count][name_len] = '\0';
                    count++;
                }
            }
        }
    }
    closedir(dir);

    *out_count = count;
    return ESP_OK;
}

esp_err_t screen_store_save_image(const char *name, const char *json_payload)
{
    if (!s_is_mounted || !name || !json_payload) return ESP_ERR_INVALID_ARG;

    ensure_directories_exist();

    char path[128];
    snprintf(path, sizeof(path), "%s/%s.json", IMAGES_DIR, name);

    size_t len = strlen(json_payload);
    esp_err_t err = write_file_replace(path, json_payload, len);
    if (err != ESP_OK) {
        ESP_LOGE(TAG, "Failed to write complete image data: %s (%u bytes) err=%s",
                 name, (unsigned)len, esp_err_to_name(err));
        return err;
    }

    ESP_LOGI(TAG, "Saved image to flash: %s (%u bytes)", name, (unsigned)len);
    return ESP_OK;
}

