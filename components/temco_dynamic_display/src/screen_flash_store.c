esp_err_t screen_store_reset_to_defaults(void)
{
    if (!s_is_mounted && !esp_spiffs_mounted(PARTITION_LABEL)) {
        return ESP_ERR_INVALID_STATE;
    }

    ESP_LOGW(TAG, "Formatting SPIFFS and restoring factory defaults");
    log_spiffs_usage("before reset");

    /* remove() does not reclaim SPIFFS pages. After a failed overwrite the
     * partition is fragmented/full, so delete+rewrite still short-writes and
     * GET returns "screen not found". Format gives a clean filesystem. */
    s_is_mounted = false;
    esp_err_t err = esp_vfs_spiffs_unregister(PARTITION_LABEL);
    if (err != ESP_OK) {
        ESP_LOGW(TAG, "SPIFFS unregister: %s", esp_err_to_name(err));
    }

    err = esp_spiffs_format(PARTITION_LABEL);
    if (err != ESP_OK) {
        ESP_LOGE(TAG, "SPIFFS format failed: %s", esp_err_to_name(err));
        mount_spiffs();
        return err;
    }

    err = mount_spiffs();
    if (err != ESP_OK) {
        return err;
    }

    seed_default_screens_if_empty();

    size_t screens_ok = count_default_files_present(DEFAULT_SCREENS, DEFAULT_SCREENS_COUNT, SCREENS_DIR);
    size_t images_ok = count_default_files_present(DEFAULT_IMAGES, DEFAULT_IMAGES_COUNT, IMAGES_DIR);

    log_spiffs_usage("after reset");
    ESP_LOGI(TAG, "Restored %u/%u default screens and %u/%u default images",
             (unsigned)screens_ok, (unsigned)DEFAULT_SCREENS_COUNT,
             (unsigned)images_ok, (unsigned)DEFAULT_IMAGES_COUNT);

    return (screens_ok == DEFAULT_SCREENS_COUNT && images_ok == DEFAULT_IMAGES_COUNT) ? ESP_OK : ESP_FAIL;
}
