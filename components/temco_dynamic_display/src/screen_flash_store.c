{
    if (!s_is_mounted || !name || !out_buf) return ESP_ERR_INVALID_ARG;

    char path[128];
    snprintf(path, sizeof(path), "%s/%s.json", IMAGES_DIR, name);

    FILE *f = fopen(path, "rb");
    if (!f) {
        return ESP_ERR_NOT_FOUND;
    }

    fseek(f, 0, SEEK_END);
    long sz = ftell(f);
    fseek(f, 0, SEEK_SET);

    if (sz <= 0) {
        fclose(f);
        return ESP_ERR_INVALID_SIZE;
    }

    char *buf = (char *)malloc(sz + 1);
    if (!buf) {
        fclose(f);
        return ESP_ERR_NO_MEM;
    }

    size_t read_bytes = fread(buf, 1, sz, f);
    fclose(f);

    buf[read_bytes] = '\0';
    *out_buf = buf;
    if (out_size) *out_size = read_bytes;

    return ESP_OK;
}

esp_err_t screen_store_delete_image(const char *name)
{
    if (!s_is_mounted || !name) return ESP_ERR_INVALID_ARG;

    char path[128];
    snprintf(path, sizeof(path), "%s/%s.json", IMAGES_DIR, name);

    if (remove(path) == 0) {
        ESP_LOGI(TAG, "Deleted image: %s", name);
        return ESP_OK;
    }

    return ESP_ERR_NOT_FOUND;
}

esp_err_t screen_store_list_images(char names[][64], size_t max_count, size_t *out_count)
{
    if (!s_is_mounted || !names || !out_count) return ESP_ERR_INVALID_ARG;

    size_t count = 0;
    DIR *dir = opendir(IMAGES_DIR);
    if (!dir) {
        *out_count = 0;
        return ESP_OK;
    }

    struct dirent *entry;
    while ((entry = readdir(dir)) != NULL && count < max_count) {
        if (entry->d_type == DT_REG || entry->d_type == DT_UNKNOWN) {
            char *dot = strrchr(entry->d_name, '.');
            if (dot && strcmp(dot, ".json") == 0) {
                size_t name_len = dot - entry->d_name;
                if (name_len < 64) {
                    strncpy(names[count], entry->d_name, name_len);
                    names[count][name_len] = '\0';
                    count++;
                }
            }
        }
    }
    closedir(dir);

    *out_count = count;
    return ESP_OK;
}

esp_err_t screen_store_reset_to_defaults(void)
{
    if (!s_is_mounted && !esp_spiffs_mounted(PARTITION_LABEL)) {
        return ESP_ERR_INVALID_STATE;
    }

    ESP_LOGW(TAG, "Formatting SPIFFS and restoring factory defaults");
    log_spiffs_usage("before reset");

    /* remove() does not reclaim SPIFFS pages. After a failed overwrite the
     * partition is fragmented/full, so delete+rewrite still short-writes and
     * GET returns "screen not found". Format gives a clean filesystem. */
    s_is_mounted = false;
    esp_err_t err = esp_vfs_spiffs_unregister(PARTITION_LABEL);
    if (err != ESP_OK) {
        ESP_LOGW(TAG, "SPIFFS unregister: %s", esp_err_to_name(err));
    }

    err = esp_spiffs_format(PARTITION_LABEL);
    if (err != ESP_OK) {
        ESP_LOGE(TAG, "SPIFFS format failed: %s", esp_err_to_name(err));
        mount_spiffs();
        return err;
    }

    err = mount_spiffs();
    if (err != ESP_OK) {
        return err;
    }

    /* the format removed the commit record: recreate it at revision 0 slot A
       before seeding, or the next boot would wipe what we seed now */
    err = screen_txn_reset_to_seed();
    if (err != ESP_OK) {
        ESP_LOGE(TAG, "Could not recreate the commit record after format (%s)", esp_err_to_name(err));
    }

    seed_default_screens_if_empty();

    size_t screens_ok = count_default_files_present(DEFAULT_SCREENS, DEFAULT_SCREENS_COUNT, SCREENS_DIR);
    size_t images_ok = count_default_files_present(DEFAULT_IMAGES, DEFAULT_IMAGES_COUNT, IMAGES_DIR);

    log_spiffs_usage("after reset");
    ESP_LOGI(TAG, "Restored %u/%u default screens and %u/%u default images",
             (unsigned)screens_ok, (unsigned)DEFAULT_SCREENS_COUNT,
             (unsigned)images_ok, (unsigned)DEFAULT_IMAGES_COUNT);

    return (screens_ok == DEFAULT_SCREENS_COUNT && images_ok == DEFAULT_IMAGES_COUNT) ? ESP_OK : ESP_FAIL;
}
